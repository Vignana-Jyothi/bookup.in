import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const sql = readFileSync(new URL('../supabase/20261025_release_readiness.sql', import.meta.url), 'utf8');
assert.match(sql, /returns jsonb language plpgsql stable security definer set search_path = ''/);
assert.match(sql, /'release','20261025-code-audit','ready'/);
assert.match(sql, /revoke all on function public\.get_release_readiness_v1\(\) from public, anon, authenticated/);
assert.match(sql, /grant execute on function public\.get_release_readiness_v1\(\) to service_role/);
assert.match(sql, /has_table_privilege\('anon',bookings_oid,'INSERT'\)/);
assert.match(sql, /has_table_privilege\('authenticated',bookings_oid,'INSERT'\)/);
assert.match(sql, /has_table_privilege\('anon',customers_oid,'SELECT'\)/);
assert.match(sql, /has_any_column_privilege\(rights.role_name,rights.relation_oid,rights.privilege_name\)/);
assert.match(sql, /p\.proname in \('create_booking_atomic','reschedule_booking_atomic','expire_legacy_booking_holds_v1'\)/);
assert.match(sql, /has_function_privilege\('authenticated',p\.oid,'EXECUTE'\)/);
assert.match(sql, /then ''awaiting_payment'' else ''not_required''/);
assert.match(sql, /status = ''cancelled'', payment_status = ''rejected''/);
assert.match(sql, /if v_current_status = ''succeeded'' then return true/);
assert.match(sql, /exception when others then/);
assert.doesNotMatch(sql, /(?:insert into|update public\.|delete from|alter table)/i, 'Readiness must not mutate application state');
console.log('Read-only database release readiness source contract passed.');
