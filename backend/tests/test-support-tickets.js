import assert from 'node:assert/strict';
import express from 'express';
import { createSupportTicketsRouter, resolveCustomerSupportContext, requireSupportAdmin } from '../server/routes/supportTickets.js';
import { isAdminPasswordSession } from '../server/routes/adminAuth.js';
import { setCustomerAccessCookie } from '../server/utils/customerAccess.js';
import { openApiDocument } from '../server/openapi.js';

process.env.DISABLE_RATE_LIMIT = 'true';
assert.equal(isAdminPasswordSession({ user_metadata: { role: 'calup_admin' } }, { aal: 'aal2' }), false);
assert.equal(isAdminPasswordSession({ app_metadata: { role: 'calup_admin' } }, { aal: 'aal1' }), false);
assert.equal(isAdminPasswordSession({ app_metadata: { role: 'calup_admin' } }, { amr: ['password'], session_id: '11111111-1111-4111-8111-111111111111' }), true, 'Eligibility only; middleware separately requires private proof and a database grant');
const providerId = '11111111-1111-4111-8111-111111111111';
const ticketId = '22222222-2222-4222-8222-222222222222';
let calls = [];
let databaseError = null;
const client = { async rpc(name, args) {
  calls.push({ name, args });
  return { data: name === 'support_customer_context_v1' ? { key: 'attempt:test', providerId } : { id: ticketId }, error: databaseError };
} };
const app = express();
app.use(express.json());
app.use('/merchant', createSupportTicketsRouter('merchant', { client, merchantAuth(req, _res, next) { req.user = { id: 'merchant-user' }; req.providerId = providerId; next(); } }));
app.use('/customer', createSupportTicketsRouter('customer', { client, customerContext: async req => req.headers['x-verified'] === 'yes' ? { key: 'attempt:verified', providerId } : null }));
app.use('/admin', requireSupportAdmin, (_req, res) => res.json({ ok: true }));
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const key = 'valid-support-key-0001';
try {
  let response = await fetch(`${base}/customer`);
  assert.equal(response.status, 401);
  assert.equal(calls.length, 0, 'Unverified customers must never reach ticket operations');
  response = await fetch(`${base}/admin`);
  assert.equal(response.status, 401);
  response = await fetch(`${base}/merchant`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': key }, body: JSON.stringify({ category: 'bug', subject: 'Bug report', body: 'Steps and expected behavior', providerId: 'attacker' }) });
  assert.equal(response.status, 422);
  assert.equal(calls.length, 0, 'Client ownership fields are rejected');
  response = await fetch(`${base}/merchant`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ category: 'bug', subject: 'Bug report', body: 'Steps and expected behavior' }) });
  assert.equal(response.status, 422, 'Writes require a retry key');
  response = await fetch(`${base}/merchant`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': key }, body: JSON.stringify({ category: 'bug', subject: 'Bug report', body: 'Steps and expected behavior' }) });
  assert.equal(response.status, 201);
  assert.equal(calls.at(-1).args.p_provider_id, providerId);
  assert.equal(calls.at(-1).args.p_actor_id, 'merchant-user');
  assert.match(response.headers.get('cache-control'), /no-store/);
  response = await fetch(`${base}/customer/${ticketId}`, { headers: { 'x-verified': 'yes' } });
  assert.equal(response.status, 200);
  assert.equal(calls.at(-1).args.p_actor_id, 'attempt:verified');
  databaseError = { message: 'NOT_FOUND' };
  response = await fetch(`${base}/merchant/${ticketId}`);
  assert.equal(response.status, 404);
  databaseError = { message: 'VERSION_CONFLICT' };
  response = await fetch(`${base}/merchant/${ticketId}/reply`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': key }, body: '{"version":1,"body":"Hello"}' });
  assert.equal(response.status, 409);
  databaseError = { message: 'Sensitive SQL details', code: 'XX000' };
  response = await fetch(`${base}/merchant/${ticketId}`);
  assert.equal(response.status, 503);
  assert.doesNotMatch(await response.text(), /Sensitive SQL/);
  databaseError = null;
  const cookies = [];
  setCustomerAccessCookie({ append(_name, value) { cookies.push(value); } }, { kind: 'reference', bookingId: 'M123456789', phone: '9876543210' });
  const cookie = `${cookies[0].split(';')[0]}; calup_attempt_v1=payment-token`;
  await resolveCustomerSupportContext({ headers: { cookie } }, client);
  assert.equal(calls.at(-1).args.p_kind, 'reference');
  await resolveCustomerSupportContext({ headers: { cookie, 'x-support-context': 'payment' } }, client);
  assert.equal(calls.at(-1).args.p_kind, 'attempt', 'Payment complaints ignore stale booking cookies');
  assert.equal(calls.at(-1).args.p_token_hash.length, 64);
  assert.equal(await resolveCustomerSupportContext({ headers: { cookie: 'calup_attempt_v1=payment-token' } }, client), null, 'A booking page must not fall back to an unrelated checkout');
  assert.equal(await resolveCustomerSupportContext({ headers: { cookie: 'calup_attempt_v1=%broken' } }, client), null);
  process.env.NODE_ENV = 'production';
  response = await fetch(`${base}/customer`, { method: 'POST', headers: { 'x-verified': 'yes', 'Content-Type': 'application/json', 'Idempotency-Key': key }, body: '{}' });
  assert.equal(response.status, 403, 'Cookie writes require a trusted origin in production');
  for (const scope of ['public','merchant','admin']) assert.ok(openApiDocument.paths[`/api/v1/${scope}/support/tickets/{id}/{action}`]);
  console.log('PASS: Ticket routes enforce session ownership, validation, retry keys, privacy, context separation, and CSRF protection.');
} finally {
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
}
